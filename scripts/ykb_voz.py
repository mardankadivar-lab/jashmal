def key():
    with open(ENV) as f:
        for ln in f:
            if ln.startswith("ELEVENLABS_API_KEY="):
                return ln.split("=", 1)[1].strip()
    raise SystemExit("No encontre ELEVENLABS_API_KEY en .env.local")


def main():
    os.makedirs(OUTDIR, exist_ok=True)
    url = f"https://api.elevenlabs.io/v1/text-to-speech/{VOICE_ID}/with-timestamps"
    body = json.dumps({
        "text": TEXT,
        "model_id": MODEL,
        "voice_settings": {"stability": 0.45, "similarity_boost": 0.75,
                           "style": 0.10, "speed": 1.06},
    }).encode()
    req = urllib.request.Request(url, data=body, method="POST",
        headers={"xi-api-key": key(), "Content-Type": "application/json"})
    print("Generando voz Martin (with-timestamps)...")
    try:
        with urllib.request.urlopen(req, timeout=240) as r:
            data = json.loads(r.read())
    except urllib.error.HTTPError as e:
        sys.exit(f"HTTP {e.code}: {e.read().decode(errors='replace')[:400]}")

    mp3 = os.path.join(OUTDIR, "ykb_voz.mp3")
    with open(mp3, "wb") as f:
        f.write(base64.b64decode(data["audio_base64"]))

    a = data["alignment"]
    chars = a["characters"]
    st = a["character_start_times_seconds"]
    en = a["character_end_times_seconds"]
    words, w, ws, we = [], "", 0.0, 0.0
    for ch, s, e in zip(chars, st, en):
        if ch == " ":
            if w:
                words.append({"w": w, "start": ws, "end": we})
            w = ""
        else:
            if not w:
                ws = s
            w += ch
            we = e
    if w:
        words.append({"w": w, "start": ws, "end": we})
    dur = en[-1] if en else 0.0

    scenes, idx = [], 0
    for i, sent in enumerate(SENTENCES):
        nw = len(sent.split())
        seg = words[idx:idx + nw]
        scenes.append({"escena": i + 1,
                       "start": round(seg[0]["start"], 3),
                       "end":   round(seg[-1]["end"], 3)})
        idx += nw

    with open(os.path.join(OUTDIR, "ykb_timing.json"), "w") as f:
        json.dump({"duration": dur, "words": words, "scenes": scenes,
                   "text": TEXT}, f, ensure_ascii=False, indent=1)

    print(f"OK  dur={dur:.2f}s  palabras={len(words)}")
    for s in scenes:
        print(f"  tiempo {s['escena']:>2}  {s['start']:6.2f} -> {s['end']:6.2f}"
              f"  ({s['end']-s['start']:5.2f}s)")
    print(f"mp3: {mp3}")


def contar():
    tot, frases = 0, 0
    for i, s in enumerate(SENTENCES, 1):
        n = len(s.split())
        tot += n
        frases += s.count(".") + s.count("?")
        print(f"  T{i:>2}  {n:>3} palabras  ~{n/2.40:5.1f} s   {s[:56]}...")
    print(f"\n  TOTAL {tot} palabras en {frases} frases"
          f"  ({tot/frases:.1f} palabras por frase)")
    print(f"  ->  ~{tot/2.40:.1f} s de voz  ->  reel ~{tot/2.40 + 2.6:.1f} s"
          f" con end-card   (objetivo 60-75 s)")


if __name__ == "__main__":
    contar() if "--contar" in sys.argv else main()
